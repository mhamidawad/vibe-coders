"""Command-line interface for the vibe-coders multi-agent framework.

Usage:

    python -m vibe_coders.cli --goal "add a config validator and test it"
    python -m vibe_coders.cli --goal "..." --files vibe_coders/supervisor.py --verbose
    vibe-coders --goal "..."   # if installed via pip (console_scripts entry point)

The CLI decomposes the goal with the Planner, creates tasks, executes them
with the appropriate specialist agents, and prints a Supervisor report.
"""

from __future__ import annotations

import argparse
import asyncio
import json
import sys
from typing import List, Optional

from .agents import (
    ArchitectureAgent,
    DebuggerAgent,
    DocumentationAgent,
    FixAgent,
    ImplementationAgent,
    PlannerAgent,
    ResearchAgent,
    ReviewAgent,
    SecurityAgent,
    TestAgent,
)
from .async_supervisor import AsyncSupervisor
from .registry import Registry

# Map role names to agent classes and a default agent id prefix.
AGENT_CLASSES = {
    "planner": (PlannerAgent, "plan"),
    "research": (ResearchAgent, "res"),
    "implementation": (ImplementationAgent, "impl"),
    "test": (TestAgent, "test"),
    "review": (ReviewAgent, "rev"),
    "fix": (FixAgent, "fix"),
    "architecture": (ArchitectureAgent, "arch"),
    "debugger": (DebuggerAgent, "dbg"),
    "security": (SecurityAgent, "sec"),
    "documentation": (DocumentationAgent, "doc"),
}

# File-ownership hints per role for tasks created from a plan.
ROLE_FILE_HINTS = {
    "implementation": ["vibe_coders/module.py"],
    "fix": ["tests/test_module.py"],
    "documentation": ["docs/module.md"],
}


def _agent_for(role: str, agent_id: str):
    cls, _prefix = AGENT_CLASSES.get(role, (ImplementationAgent, "impl"))
    return cls(agent_id)


def _file_owns_for(role: str, subtask: dict) -> list:
    explicit = subtask.get("output_files")
    if explicit:
        return explicit
    hints = ROLE_FILE_HINTS.get(role, [])
    return list(hints)


def _default_content(role: str, title: str) -> str:
    """Generate sensible starter content for a new file based on role and title."""
    safe_name = "".join(c if c.isalnum() else "_" for c in title).strip("_") or "module"
    if role == "implementation":
        return (
            f'"""Auto-generated by vibe-coders for: {title}."""\n'
            f"from __future__ import annotations\n\n"
            f"from typing import Any, Dict, List\n\n\n"
            f"def run({safe_name}: Dict[str, Any]) -> List[str]:\n"
            f'    """Execute the task described by: {title}"""\n'
            f"    return []\n"
        )
    if role == "fix":
        return f"# Fix for: {title}\n# Applied by vibe-coders fix agent\n"
    if role == "documentation":
        return f"# {title}\n\nGenerated by the documentation agent.\n"
    if role == "test":
        return (
            f"# Tests for: {title}\n"
            f"import unittest\n\n"
            f"class Test{safe_name.title()}(unittest.TestCase):\n"
            f"    def test_placeholder(self):\n"
            f"        self.assertTrue(True)\n"
        )
    return f"# {title}\n"


async def run_goal(
    goal: str,
    files: Optional[List[str]] = None,
    max_active: int = 3,
    max_impl: int = 2,
    verbose: bool = False,
) -> dict:
    """Execute a goal end-to-end through the multi-agent framework.

    Returns the Supervisor report dict.
    """
    files = files or []
    sup = AsyncSupervisor(
        Registry(max_active_agents=max_active, max_impl_concurrent=max_impl)
    )

    # 1. Planner decomposes the goal.
    plan = await sup.plan_goal(goal, files=files)
    if verbose:
        print(f"[planner] {plan['detail']} (confidence={plan['confidence']:.2f})", file=sys.stderr)
        for st in plan.get("findings", []):
            print(
                f"   - {st['id']}: {st['title']} -> {st['role']} (effort={st['effort']})",
                file=sys.stderr,
            )

    # 2. Create tasks from the plan.
    tasks = await sup.create_tasks_from_plan(plan)

    # 3. Execute each task with its assigned agent.
    executions = []
    agent_counter: dict[str, int] = {}
    for t in tasks:
        role = t.agent_role
        agent_counter[role] = agent_counter.get(role, 0) + 1
        agent_id = f"{role}-{agent_counter[role]}"
        agent = _agent_for(role, agent_id)
        file_path = _file_owns_for(role, t.result or {})[0] if t.file_owns else None
        content = _default_content(role, t.title)
        context = {
            "path": file_path,
            "content": content,
            "goal": goal,
            "files": files,
            "task_title": t.title,
        }
        # delegation may fail if concurrency limits are hit; that's OK,
        # run_concurrent will still attempt and report.
        await sup.delegate(t.id, agent)  # type: ignore[arg-type]
        executions.append((t.id, agent, context))

    results = await sup.run_concurrent(executions)

    if verbose:
        for tid, res in zip([t.id for t in tasks], results):
            print(
                f"  {tid}: {res.get('status')} confidence={res.get('confidence'):.2f}",
                file=sys.stderr,
            )

    return sup.report()


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(
        prog="vibe-coders",
        description="Veteran-Grade Specialist Agents: multi-agent orchestration CLI.",
    )
    parser.add_argument(
        "--goal",
        required=True,
        help="High-level goal to accomplish (e.g. 'add a config validator and test it').",
    )
    parser.add_argument(
        "--files",
        nargs="*",
        default=[],
        help="File paths to pass as context to the planner/agents.",
    )
    parser.add_argument(
        "--max-active",
        type=int,
        default=3,
        help="Maximum concurrent active agents (default: 3).",
    )
    parser.add_argument(
        "--max-impl",
        type=int,
        default=2,
        help="Maximum concurrent implementation-role agents (default: 2).",
    )
    parser.add_argument(
        "--verbose",
        action="store_true",
        help="Print detailed progress to stderr.",
    )
    parser.add_argument(
        "--json",
        action="store_true",
        help="Print the Supervisor report as JSON to stdout.",
    )

    args = parser.parse_args(argv)

    try:
        report = asyncio.run(
            run_goal(
                goal=args.goal,
                files=args.files,
                max_active=args.max_active,
                max_impl=args.max_impl,
                verbose=args.verbose,
            )
        )
    except Exception as exc:  # noqa: BLE001
        print(f"ERROR: {type(exc).__name__}: {exc}", file=sys.stderr)
        return 1

    if args.json:
        print(json.dumps(report, indent=2))
    else:
        print(f"active_agents={report['active_agents']} / {report['max_active_agents']}")
        print(f"impl_busy={report['impl_busy']} / {report['max_impl_concurrent']}")
        for tid, t in report["tasks"].items():
            print(
                f"  {tid} [{t['role']}]: {t['status']} "
                f"confidence={t['confidence']} strategy_change={t['strategy_change']}"
            )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
